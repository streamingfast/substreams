package codegen

import (
	"os"
	"path/filepath"
	"testing"
)

const testMarker = "// @generated by substreams"

func tempGeneratedFile(t *testing.T, content string) *generatedFile {
	t.Helper()

	path := filepath.Join(t.TempDir(), "mod.rs")
	if content != "" {
		if err := os.WriteFile(path, []byte(content), 0644); err != nil {
			t.Fatalf("seeding %q: %v", path, err)
		}
	}
	return newGeneratedFile(path, testMarker)
}

func TestGeneratedFileOwnership(t *testing.T) {
	for _, tt := range []struct {
		name    string
		content string
		want    ownership
	}{
		{"absent", "", ownershipAbsent},
		{"ours", testMarker + "\npub mod a {}\n", ownershipOurs},
		{"ours, no trailing newline", testMarker, ownershipOurs},
		{"ours, carriage returns", testMarker + "\r\npub mod a {}\r\n", ownershipOurs},
		{"hand written", "// mine\npub mod a {}\n", ownershipForeign},
		// Annotating the marker line is how someone says "I edited this, leave it
		// alone". A prefix match would read it as ours and overwrite their work.
		{"marker with a trailing note", testMarker + " - edited by hand, do not regen\n", ownershipForeign},
		{"prost-crate output", "// @generated\npub mod a {}\n", ownershipForeign},
		{"empty", " ", ownershipForeign},
		{"marker not on the first line", "// mine\n" + testMarker + "\n", ownershipForeign},
	} {
		t.Run(tt.name, func(t *testing.T) {
			got, err := tempGeneratedFile(t, tt.content).ownership()
			if err != nil {
				t.Fatalf("ownership: %v", err)
			}
			if got != tt.want {
				t.Errorf("ownership = %v, want %v", got, tt.want)
			}
		})
	}
}

func TestGeneratedFileWriteRefusesForeignFile(t *testing.T) {
	const original = "// hand written\npub mod mine {}\n"
	f := tempGeneratedFile(t, original)

	changed, err := f.write(testMarker + "\npub mod theirs {}\n")
	if err != nil {
		t.Fatalf("write: %v", err)
	}
	if changed {
		t.Error("write reported a change to a file it does not own")
	}

	got, err := os.ReadFile(f.path)
	if err != nil {
		t.Fatalf("reading back: %v", err)
	}
	if string(got) != original {
		t.Errorf("foreign file was modified:\n%s", got)
	}
}

func TestGeneratedFileWriteReportsWhetherItChanged(t *testing.T) {
	content := testMarker + "\npub mod a {}\n"
	f := tempGeneratedFile(t, "")

	changed, err := f.write(content)
	if err != nil {
		t.Fatalf("first write: %v", err)
	}
	if !changed {
		t.Error("creating the file should report a change")
	}

	// Rewriting identical content must not touch the file: the mtime drives a rebuild.
	changed, err = f.write(content)
	if err != nil {
		t.Fatalf("second write: %v", err)
	}
	if changed {
		t.Error("rewriting identical content should report no change")
	}

	changed, err = f.write(testMarker + "\npub mod b {}\n")
	if err != nil {
		t.Fatalf("third write: %v", err)
	}
	if !changed {
		t.Error("new content should report a change")
	}
}

func TestGeneratedFileWriteLeavesMtimeAloneWhenUnchanged(t *testing.T) {
	content := testMarker + "\npub mod a {}\n"
	f := tempGeneratedFile(t, content)

	before, err := os.Stat(f.path)
	if err != nil {
		t.Fatalf("stat: %v", err)
	}

	if _, err := f.write(content); err != nil {
		t.Fatalf("write: %v", err)
	}

	after, err := os.Stat(f.path)
	if err != nil {
		t.Fatalf("stat: %v", err)
	}
	if !before.ModTime().Equal(after.ModTime()) {
		t.Errorf("mtime changed on an identical write: %v -> %v", before.ModTime(), after.ModTime())
	}
}

func TestGeneratedFileOwnershipSurfacesReadErrors(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "mod.rs")
	if err := os.Mkdir(path, 0755); err != nil {
		t.Fatalf("mkdir: %v", err)
	}

	if _, err := newGeneratedFile(path, testMarker).ownership(); err == nil {
		t.Error("expected an error when the path is not a regular file")
	}
}
