package codegen

import (
	"fmt"
	"sort"
	"strings"
)

// Rendering a proto package tree as Rust module declarations. The escaping rules
// mirror buffa's own codegen, in buffa-codegen/src/idents.rs.

const (
	generatedModHeader = "// @generated by substreams"

	// rootModuleFile is what buffa names the output of a descriptor that declares no
	// package; it is included at the root of the tree rather than nested.
	rootModuleFile = "__buffa"
)

// rustKeywords are the identifiers that cannot appear bare as a module name.
// A proto package segment is free to use any of them, `sf.solana.type.v1` being a real
// example, so each segment is escaped the way buffa's own codegen does it.
var rustKeywords = map[string]bool{
	"as": true, "break": true, "const": true, "continue": true, "crate": true,
	"dyn": true, "else": true, "enum": true, "extern": true, "false": true,
	"fn": true, "for": true, "if": true, "impl": true, "in": true, "let": true,
	"loop": true, "match": true, "mod": true, "move": true, "mut": true,
	"pub": true, "ref": true, "return": true, "self": true, "Self": true,
	"static": true, "struct": true, "super": true, "trait": true, "true": true,
	"type": true, "unsafe": true, "use": true, "where": true, "while": true,
	"async": true, "await": true, "dyn_": true, "abstract": true, "become": true,
	"box": true, "do": true, "final": true, "macro": true, "override": true,
	"priv": true, "typeof": true, "unsized": true, "virtual": true, "yield": true,
	"try": true, "gen": true,
}

// cannotBeRawIdent lists the keywords Rust refuses to accept as `r#name`.
var cannotBeRawIdent = map[string]bool{
	"crate": true, "self": true, "Self": true, "super": true,
}

func escapeModIdent(name string) string {
	if !rustKeywords[name] {
		return name
	}
	if cannotBeRawIdent[name] {
		return name + "_"
	}
	return "r#" + name
}

// modNode is one level of the Rust module tree: the generated files to include at
// this level, and the child modules below it.
type modNode struct {
	includes []string
	children map[string]*modNode
}

func newModNode() *modNode {
	return &modNode{children: map[string]*modNode{}}
}

// insert places a generated file at the path given by its proto package. An empty
// path puts the include at this level, which is how a package-less descriptor ends
// up at the root of the tree.
func (n *modNode) insert(path []string, include string) {
	node := n
	for _, segment := range path {
		child, ok := node.children[segment]
		if !ok {
			child = newModNode()
			node.children[segment] = child
		}
		node = child
	}
	node.includes = append(node.includes, include)
}

// render writes this level and everything beneath it, children in a stable order.
func (n *modNode) render(out *strings.Builder, depth int) {
	indent := strings.Repeat("    ", depth)

	for _, include := range n.includes {
		fmt.Fprintf(out, "%sinclude!(%q);\n", indent, include+".mod.rs")
	}

	names := make([]string, 0, len(n.children))
	for name := range n.children {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		fmt.Fprintf(out, "%spub mod %s {\n", indent, escapeModIdent(name))
		n.children[name].render(out, depth+1)
		fmt.Fprintf(out, "%s}\n", indent)
	}
}

// renderModuleTree renders `mod.rs`: a `pub mod` per proto package segment, each
// wrapping an `include!` of the file buffa generated for that package.
//
// rootFiles are generated files that belong at the top level rather than inside a
// module, which is where a descriptor declaring no package ends up.
//
// The output is deterministic regardless of the order the inputs arrive in: the tree
// is built first, then walked with children sorted by name.
func renderModuleTree(packages []string, rootFiles []string) string {
	root := newModNode()
	for _, file := range rootFiles {
		root.insert(nil, file)
	}
	for _, pkgName := range packages {
		root.insert(strings.Split(pkgName, "."), pkgName)
	}

	var out strings.Builder
	out.WriteString(generatedModHeader + "\n#![allow(clippy::all)]\n")
	root.render(&out, 0)

	return out.String()
}
